# source_server.py — 자료실 MCP 서버 (Day 4 Part 3-확장)
# 분석 팀이 쓸 원문 자료를 MCP 표준으로 내준다.
# 직접 실행하지 않는다: 클라이언트 스크립트가 이 파일을 stdio로 띄워 연결한다 (2과목 Day 7과 같은 방식).
from mcp.server.fastmcp import FastMCP

mcp = FastMCP("자료실", log_level="WARNING")  # 요청마다 찍히는 INFO 로그를 끈다 → 클라이언트 출력이 잘 보인다

SOURCES = {
    "달빛 도서관": """[내부 소개 자료] 달빛 도서관
달빛 도서관은 밤 10시부터 새벽 2시까지 여는 무인 야간 도서관이다.
서울 마포구에 1호점이 있으며, 좌석은 총 48석이다.
입장은 월 구독제이며, 구독료는 월 19,900원이다.
사서 대신 안내 로봇 '루나'가 책 추천과 반납을 돕는다.
조용한 환경을 위해 통화와 취식은 금지된다.
회원의 62%가 20~30대 직장인이다.
2026년 12월에 부산 2호점이 문을 열 예정이다.""",
    "새벽 수영 클럽": """[내부 소개 자료] 새벽 수영 클럽
새벽 수영 클럽은 평일 오전 5시 30분부터 7시까지 운영하는 직장인 수영 모임이다.
장소는 성수동의 실내 수영장이며, 레인 3개를 통째로 빌려 쓴다.
월 회비는 89,000원이고, 강습료가 포함되어 있다.
초급반·중급반·자유수영반 세 반으로 나뉜다.
수료 기준을 통과하면 한강 야외 수영 행사에 참가할 수 있다.
현재 회원은 74명이며 대기자가 30명이 넘는다.""",
}


@mcp.tool()
def list_sources() -> list[str]:
    """자료실에 있는 자료 이름 목록을 돌려준다."""
    return list(SOURCES)


@mcp.tool()
def get_source(name: str) -> str:
    """자료 이름으로 원문을 돌려준다. 없는 이름이면 목록을 알려 준다."""
    if name not in SOURCES:
        # 예외 대신 안내 문구를 돌려준다 → 클라이언트(에이전트)가 다음 행동을 정할 수 있다
        return f"'{name}' 자료가 없습니다. 있는 자료: {', '.join(SOURCES)}"
    return SOURCES[name]


if __name__ == "__main__":
    mcp.run(transport="stdio")  # 로컬 stdio로 대기
